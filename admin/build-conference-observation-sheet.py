"""Build the GEAP 103 conference observation sheet (Markdown and one-page PDF).

Run from the repository root:
    uv run --with reportlab --with pypdf python admin/build-conference-observation-sheet.py
"""
from pathlib import Path

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import letter, landscape
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import inch
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from pypdf import PdfReader

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
FONTS = ROOT / "materials/day-01/assets"
MD_OUT = HERE / "conference-observation-sheet.md"
PDF_OUT = ROOT / "output/pdf/conference-observation-sheet.pdf"
INK = HexColor("#191919")
ACCENT = HexColor("#800020")
RULE = HexColor("#cbbfc2")
SHADE = HexColor("#f4eff0")

TITLE = "Conference observation sheet"
HEADER = "GEAP 103  |  Observer: ____________________  |  Date: ____________  |  Section: ____________"
INSTRUCTION = (
    "Listen while the student shows something and explains it. Note the outcome they showed, "
    "how well they showed it, and what you saw. Write initials, not full names. "
    "If two of us observe the same conference, rate it separately and compare afterwards."
)
OUTCOMES = ("Outcomes:  1 Files and versions  ·  2 Troubleshoot  ·  3 Guide AI  ·  4 Evaluate AI  ·  5 Communicate about technical work  ·  "
            "6 Produce digital products  ·  7 Collaborate with peers.  For 3 and 4, ask: \"What did you ask the AI? What did you keep, change, or reject, and why?\"")
REQUIRED = "Required checks, across all conferences:  R = got back an earlier version  ·  T = solved a technical problem or described it clearly enough to get help  ·  P = changed a classmate's work, got a comment, replied"
LEVELS = [
    ("4", "Does it on their own and explains what they did and why.",
     "Restores an earlier version and says which one and how they know it's right."),
    ("3", "Does it on their own, but the explanation has gaps.",
     "Restores it, but can't quite say how they know it's the right version."),
    ("2", "Does part of it, or gets there only with prompting.",
     "Finds the version history, but needs help to restore the right version."),
    ("1", "Tries, but there's little to show.",
     "The file doesn't open, or they can't tell which version is which."),
    ("0", "Hasn't shown it yet.", "Nothing to show for this outcome yet."),
]
COLUMNS = ["Time", "Student initials", "What they showed", "Outcome", "Level", "Check", "Note or next question"]
ROWS = 11


def write_markdown():
    lines = [
        f"# {TITLE}", "",
        "<!-- Generated by admin/build-conference-observation-sheet.py; edit the script, not this file. -->", "",
        HEADER, "", INSTRUCTION, "", OUTCOMES, "", REQUIRED, "",
        "| Level | Meaning | Example: getting back an earlier version (outcome 1) |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {m} | {e} |" for n, m, e in LEVELS]
    lines += ["", "Levels 3 and 4 count once shown twice, at least once without AI (a conference or in-class writing). One showing without AI is enough for level 2.", "",
              "| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    lines += ["| " + " | ".join([" "] * len(COLUMNS)) + " |" for _ in range(ROWS)]
    MD_OUT.write_text("\n".join(lines) + "\n")


def build_pdf():
    pdfmetrics.registerFont(TTFont("EG", FONTS / "EBGaramond-Regular.ttf"))
    pdfmetrics.registerFont(TTFont("EGItalic", FONTS / "EBGaramond-Italic.ttf"))
    body = ParagraphStyle("body", fontName="EG", fontSize=10.5, leading=12.5, textColor=INK)
    small = ParagraphStyle("small", parent=body, fontSize=9.5, leading=11)
    title = ParagraphStyle("title", parent=body, fontSize=18, leading=21, textColor=ACCENT)
    head = ParagraphStyle("head", parent=small, textColor=ACCENT)

    PDF_OUT.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(str(PDF_OUT), pagesize=landscape(letter),
                            leftMargin=0.5 * inch, rightMargin=0.5 * inch,
                            topMargin=0.45 * inch, bottomMargin=0.4 * inch,
                            title=TITLE, author="GEAP 103")
    width = doc.width
    story = [Paragraph(TITLE, title), Spacer(1, 2), Paragraph(HEADER, small), Spacer(1, 4),
             Paragraph(INSTRUCTION, body), Spacer(1, 3), Paragraph(OUTCOMES, small),
             Paragraph(REQUIRED, small), Spacer(1, 5)]

    level_data = [[Paragraph("Level", head), Paragraph("Meaning", head),
                   Paragraph("Example: getting back an earlier version (outcome 1)", head)]]
    level_data += [[Paragraph(n, body), Paragraph(m, small), Paragraph(e, small)] for n, m, e in LEVELS]
    levels = Table(level_data, colWidths=[0.5 * inch, 3.6 * inch, width - 4.1 * inch])
    levels.setStyle(TableStyle([
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, RULE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 1.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5),
    ]))
    story += [levels, Spacer(1, 2),
              Paragraph("Levels 3 and 4 count once shown twice, at least once without AI (a conference or in-class writing). One showing without AI is enough for level 2.", small),
              Spacer(1, 6)]

    widths = [0.6, 0.95, 2.6, 0.7, 0.55, 0.55]
    widths = [w * inch for w in widths] + [width - sum(w * inch for w in widths)]
    obs_data = [[Paragraph(c, head) for c in COLUMNS]] + [[""] * len(COLUMNS) for _ in range(ROWS)]
    obs = Table(obs_data, colWidths=widths, rowHeights=[16] + [27] * ROWS)
    obs.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, RULE),
        ("BACKGROUND", (0, 0), (-1, 0), SHADE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(obs)
    doc.build(story)
    pages = len(PdfReader(PDF_OUT).pages)
    assert pages == 1, f"Observation sheet runs to {pages} pages"


if __name__ == "__main__":
    write_markdown()
    build_pdf()
    print("wrote", MD_OUT.relative_to(ROOT), "and", PDF_OUT.relative_to(ROOT))
